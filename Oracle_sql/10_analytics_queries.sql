

/* Q1. Find the total number of customers. */

SELECT COUNT(*) AS total_customers
FROM customer;


/* Q2. Find the total number of products. */

SELECT COUNT(*) AS total_products
FROM product;


/* Q3. Find the total number of dark stores. */

SELECT COUNT(*) AS total_stores
FROM dark_store;


/* Q4. Find the total number of orders. */

SELECT COUNT(*) AS total_orders
FROM orders;


/* Q5. Find the total revenue generated. */

SELECT SUM(total_amount) AS total_revenue
FROM orders;


/* Q6. Find the average order value (AOV). */

SELECT ROUND(AVG(total_amount), 2) AS average_order_value
FROM orders;


/* Q7. Find the minimum and maximum order value. */

SELECT
    MIN(total_amount) AS minimum_order_value,
    MAX(total_amount) AS maximum_order_value
FROM orders;


/* Q8. Find the total quantity of products sold. */

SELECT SUM(quantity) AS total_quantity_sold
FROM order_items;


/* Q9. Find the average product price. */

SELECT ROUND(AVG(price), 2) AS average_product_price
FROM product;


/* Q10. Find the total number of successful payments. */

SELECT COUNT(*) AS successful_payments
FROM payment
WHERE payment_status = 'SUCCESS';






/* Q11. Find the number of orders by order status. */

SELECT
    order_status,
    COUNT(*) AS total_orders
FROM orders
GROUP BY order_status
ORDER BY total_orders DESC;


/* Q12. Find revenue by order status. */

SELECT
    order_status,
    SUM(total_amount) AS total_revenue
