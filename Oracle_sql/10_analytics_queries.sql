    order_id,
    total_amount
FROM (
    SELECT
        o.*,
        ROW_NUMBER() OVER (
            PARTITION BY store_id
            ORDER BY total_amount DESC
        ) AS rn
    FROM orders o
)
WHERE rn <= 3
ORDER BY
    store_id,
    total_amount DESC;






/* Q148. Find customers whose total spending is greater
       than the average customer spending using a CTE. */

WITH customer_spending AS (
    SELECT
        customer_id,
        SUM(total_amount) AS total_spending
    FROM orders
    GROUP BY customer_id
),
average_spending AS (
    SELECT
        AVG(total_spending) AS avg_spending
    FROM customer_spending
)
SELECT
    c.customer_id,
    c.customer_name,
    cs.total_spending
FROM customer c
JOIN customer_spending cs
    ON c.customer_id = cs.customer_id
CROSS JOIN average_spending a
WHERE cs.total_spending > a.avg_spending
ORDER BY cs.total_spending DESC;


/* Q149. Find the top-revenue product in each category
       using a CTE. */

WITH product_revenue AS (
    SELECT
        p.product_id,
        p.product_name,
        p.category_id,
        SUM(oi.quantity * oi.item_price) AS total_revenue
    FROM product p
    JOIN order_items oi
        ON p.product_id = oi.product_id
    GROUP BY
        p.product_id,
        p.product_name,
        p.category_id
),
ranked_products AS (
    SELECT
        product_id,
        product_name,
        category_id,
        total_revenue,
        RANK() OVER (
            PARTITION BY category_id
            ORDER BY total_revenue DESC
        ) AS rnk
    FROM product_revenue
)
SELECT
    category_id,
    product_id,
    product_name,
    total_revenue
FROM ranked_products
WHERE rnk = 1
ORDER BY category_id;


/* Q150. Create a complete customer lifetime value analysis.

       Includes:
       - Total orders
       - Total spending
       - Average order value
       - Highest order value
       - Customer rank
       - Percentage contribution to total revenue
*/

WITH customer_metrics AS (
    SELECT
        c.customer_id,
        c.customer_name,
        COUNT(o.order_id) AS total_orders,
        SUM(o.total_amount) AS total_spending,
        ROUND(AVG(o.total_amount), 2) AS avg_order_value,
        MAX(o.total_amount) AS max_order_value
    FROM customer c
    JOIN orders o
        ON c.customer_id = o.customer_id
    GROUP BY
        c.customer_id,
        c.customer_name
)
SELECT
    customer_id,
    customer_name,
    total_orders,
    total_spending,
    avg_order_value,
    max_order_value,

    DENSE_RANK() OVER (
        ORDER BY total_spending DESC
    ) AS customer_rank,

    ROUND(
        total_spending /
        SUM(total_spending) OVER () * 100,
        2
    ) AS revenue_contribution_pct

FROM customer_metrics
ORDER BY customer_rank;

