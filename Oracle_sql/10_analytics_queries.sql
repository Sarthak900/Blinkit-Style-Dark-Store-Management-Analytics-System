/* Q24. Find the highest-revenue store in each city. */

SELECT
    city,
    store_name,
    total_revenue
FROM (
    SELECT
        ds.city,
        ds.store_name,
        SUM(o.total_amount) AS total_revenue,
        RANK() OVER (
            PARTITION BY ds.city
            ORDER BY SUM(o.total_amount) DESC
        ) AS rnk
    FROM dark_store ds
    JOIN orders o
        ON ds.store_id = o.store_id
    GROUP BY
        ds.city,
        ds.store_name
)
WHERE rnk = 1;


/* Q25. Find stores whose revenue is above the average store revenue. */

SELECT
    store_id,
    store_name,
    total_revenue
FROM (
    SELECT
        ds.store_id,
        ds.store_name,
        SUM(o.total_amount) AS total_revenue
    FROM dark_store ds
    JOIN orders o
        ON ds.store_id = o.store_id
    GROUP BY
        ds.store_id,
        ds.store_name
)
WHERE total_revenue >
(
    SELECT AVG(total_revenue)
    FROM (
        SELECT
            store_id,
            SUM(total_amount) AS total_revenue
        FROM orders
        GROUP BY store_id
    )
)
ORDER BY total_revenue DESC;



